def _repeated_script(url, dataset, pagination, max_pages, delay) -> tuple[str, list[str]]:
    selector = dataset.get("selector") or "div"
    template = pagination.get("url_template")
    pages_block = (
        f'''URL_TEMPLATE = "{template}"
PAGES = [URL_TEMPLATE.replace("{{page}}", str(p)) for p in range({pagination.get("start", 1)}, {pagination.get("start", 1)} + {max_pages})]'''
        if template and max_pages > 1
        else f'PAGES = ["{url}"]'
    )
    body = f'''import httpx
import pandas as pd
from lxml import html as lxml_html
from urllib.parse import urljoin

HEADERS = {{"User-Agent": "research-reproduction-script"}}
ITEM_SELECTOR = "{selector}"
{pages_block}


def parse_item(node, base_url):
    row = {{}}
    heading = node.cssselect("h1, h2, h3, h4, h5")
    if heading:
        row["title"] = " ".join(heading[0].text_content().split())
    link = node.cssselect("a[href]")
    if link:
        row["link"] = urljoin(base_url, link[0].get("href"))
    time_node = node.cssselect("time")
    if time_node:
        row["date"] = time_node[0].get("datetime") or time_node[0].text_content().strip()
    if not row:
        row["text"] = " ".join(node.text_content().split())[:400]
    return row


rows = []
with httpx.Client(headers=HEADERS, timeout=30.0, follow_redirects=True) as client:
    for page_url in PAGES:
        response = client.get(page_url)
        response.raise_for_status()
        tree = lxml_html.fromstring(response.text)
        items = tree.cssselect(ITEM_SELECTOR)
        if not items:
            break
        rows.extend(parse_item(item, page_url) for item in items)
        time.sleep(REQUEST_DELAY_SECONDS)

df = pd.DataFrame(rows)
print(df.shape)
df.to_csv("dataset.csv", index=False)
'''
    return body, ["httpx", "pandas", "lxml", "cssselect"]


def _file_script(url, dataset, pagination, max_pages, delay) -> tuple[str, list[str]]:
    target = dataset.get("api_url") or url
    body = f'''import io

import httpx
import pandas as pd

FILE_URL = "{target}"
HEADERS = {{"User-Agent": "research-reproduction-script"}}

with httpx.Client(headers=HEADERS, timeout=60.0, follow_redirects=True) as client:
    response = client.get(FILE_URL)
    response.raise_for_status()

buffer = io.BytesIO(response.content)
if FILE_URL.endswith((".xlsx", ".xls")):
    df = pd.read_excel(buffer)
elif FILE_URL.endswith(".parquet"):
    df = pd.read_parquet(buffer)
elif FILE_URL.endswith((".json", ".jsonl")):
    df = pd.read_json(buffer, lines=FILE_URL.endswith(".jsonl"))
else:
    df = pd.read_csv(buffer, sep=None, engine="python")

print(df.shape)
df.to_csv("dataset.csv", index=False)
'''
    return body, ["httpx", "pandas"]


