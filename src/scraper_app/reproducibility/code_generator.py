def _crawl4ai_script(url, dataset, pagination, max_pages, delay) -> tuple[str, list[str]]:
    body = f'''import asyncio
import io

import pandas as pd
from crawl4ai import AsyncWebCrawler

SOURCE_URL = "{url}"


async def main():
    async with AsyncWebCrawler(verbose=False) as crawler:
        result = await crawler.arun(url=SOURCE_URL)
    html = getattr(result, "cleaned_html", "") or getattr(result, "html", "")
    tables = pd.read_html(io.StringIO(html), flavor="lxml")
    df = tables[0] if tables else pd.DataFrame([{{"markdown": str(result.markdown)}}])
    print(df.shape)
    df.to_csv("dataset.csv", index=False)


asyncio.run(main())
'''
    return body, ["crawl4ai", "pandas", "lxml"]


def _document_script(url, dataset, pagination, max_pages, delay) -> tuple[str, list[str]]:
    body = f'''import httpx
import pandas as pd
import fitz  # PyMuPDF

DOCUMENT_URL = "{url}"
HEADERS = {{"User-Agent": "research-reproduction-script"}}

with httpx.Client(headers=HEADERS, timeout=60.0, follow_redirects=True) as client:
    response = client.get(DOCUMENT_URL)
    response.raise_for_status()

rows = []
with fitz.open(stream=response.content, filetype="pdf") as document:
    for index in range(document.page_count):
        page = document.load_page(index)
        rows.append({{"page": index + 1, "text": page.get_text("text")}})

df = pd.DataFrame(rows)
print(df.shape)
df.to_csv("dataset.csv", index=False)
'''
    return body, ["httpx", "pandas", "pymupdf"]
