"""Generate a runnable Python reproducer (spec section 35).

The generated script matches the engine that actually ran:

* ``json_api``      → httpx + pagination loop
* ``table``         → httpx + pandas.read_html
* ``repeated_dom``  → httpx + lxml selectors
* ``direct_file``   → httpx + the matching pandas reader
* ``article``       → httpx + trafilatura
* ``playwright``    → Playwright script
* ``crawl4ai``      → Crawl4AI script

Credentials are never embedded; the script reads them from environment
variables.
"""

from __future__ import annotations

from typing import Any

HEADER = '''"""Reproduction script generated by Smart Research Web Scraper {version}.

Developed by Dr Merwan Roudane (https://github.com/merwanroudane).

Source:  {url}
Engine:  {engine}
Created: {created}

Dependencies:
    pip install {deps}

Any credentials are read from environment variables; none are stored in this file.
"""

from __future__ import annotations
{stdlib_imports}
'''


def _insert_rate_limit(body: str, delay: float) -> str:
    """Place the delay constant after the body imports so the script stays PEP 8."""
    line = f"REQUEST_DELAY_SECONDS = {delay}  # be polite to the source"
    lines = body.splitlines()
    last_import = -1
    for index, text in enumerate(lines[:20]):
        if text.startswith(("import ", "from ")):
            last_import = index
    if last_import < 0:
        return f"{line}\n\n{body}"
    lines.insert(last_import + 1, "\n" + line)
    return "\n".join(lines)


def generate(
    *,
    engine: str,
    url: str,
    recipe: dict[str, Any],
    columns: list[str] | None = None,
    version: str = "0.1.0",
    created: str = "",
) -> str:
    """Return the full Python source of the reproducer."""
    dataset = recipe.get("dataset", {}) or {}
    pagination = recipe.get("pagination", {}) or {}
    limits = recipe.get("limits", {}) or {}
    max_pages = int(limits.get("max_pages", 1) or 1)
    delay = 0.7

    builders = {
        "json_api": _json_api_script,
        "table": _table_script,
        "repeated_dom": _repeated_script,
        "direct_file": _file_script,
        "article": _article_script,
        "feed": _feed_script,
        "links": _links_script,
        "structured": _structured_script,
        "playwright": _playwright_script,
        "crawl4ai": _crawl4ai_script,
        "document": _document_script,
    }
    builder = builders.get(engine, _table_script)
    body, deps = builder(url, dataset, pagination, max_pages, delay)

    # Only import what the generated body actually uses.
    stdlib = [name for name in ("os", "time") if f"{name}." in body]
    head = HEADER.format(
        version=version,
        url=url,
        engine=engine,
        created=created,
        deps=" ".join(deps),
        stdlib_imports="\n" + "\n".join(f"import {name}" for name in stdlib) + "\n"
        if stdlib
        else "",
    )
    return head + _insert_rate_limit(body, delay)


# --------------------------------------------------------------------------- scripts
def _json_api_script(url, dataset, pagination, max_pages, delay) -> tuple[str, list[str]]:
    api_url = dataset.get("api_url") or url
    records_path = dataset.get("records_path")
    template = pagination.get("url_template")
    ptype = pagination.get("type", "none")

    walk = ""
    if records_path:
        walk = f'''
def walk(payload, path="{records_path}"):
    node = payload
    for part in path.split("."):
        if not part:
            continue
        if isinstance(node, dict):
            node = node.get(part)
        else:
            return []
    return node or []
'''
    else:
        walk = """
def walk(payload, path=None):
    if isinstance(payload, list):
        return payload
    if isinstance(payload, dict):
        for value in payload.values():
            if isinstance(value, list) and value and isinstance(value[0], dict):
                return value
    return []
"""

    if ptype == "page_number" and template:
        loop = f'''
URL_TEMPLATE = "{template}"
MAX_PAGES = {max_pages}

rows = []
with httpx.Client(headers=HEADERS, timeout=30.0, follow_redirects=True) as client:
    for page in range({pagination.get("start", 1)}, {pagination.get("start", 1)} + MAX_PAGES):
        response = client.get(URL_TEMPLATE.replace("{{page}}", str(page)))
        response.raise_for_status()
        batch = walk(response.json())
        if not batch:
            break
        rows.extend(batch)
        time.sleep(REQUEST_DELAY_SECONDS)
'''
    else:
        loop = f'''
API_URL = "{api_url}"

rows = []
with httpx.Client(headers=HEADERS, timeout=30.0, follow_redirects=True) as client:
    response = client.get(API_URL)
    response.raise_for_status()
    rows = walk(response.json())
'''

    body = f"""import httpx
import pandas as pd

HEADERS = {{"User-Agent": "research-reproduction-script"}}
{walk}{loop}
df = pd.json_normalize(rows)
print(df.shape)
df.to_csv("dataset.csv", index=False)
"""
    return body, ["httpx", "pandas"]


